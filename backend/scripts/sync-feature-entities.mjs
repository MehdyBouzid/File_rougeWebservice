import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const backendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const resources = [
  'patients',
  'measurements',
  'thresholds',
  'alerts',
  'consents',
  'caregivers',
];

async function entityFiles(folder) {
  const files = [];
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const path = resolve(folder, entry.name);
    if (entry.isDirectory()) files.push(...(await entityFiles(path)));
    else if (entry.name.endsWith('.entity.ts')) files.push(path);
  }
  return files.sort();
}

function exportedEntities(source, filename) {
  const file = ts.createSourceFile(
    filename,
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const decorators = new Set();
  for (const statement of file.statements) {
    if (
      !ts.isImportDeclaration(statement) ||
      !ts.isStringLiteral(statement.moduleSpecifier) ||
      statement.moduleSpecifier.text !== 'typeorm'
    )
      continue;
    const bindings = statement.importClause?.namedBindings;
    if (!bindings || !ts.isNamedImports(bindings)) continue;
    for (const binding of bindings.elements) {
      const imported = binding.propertyName?.text ?? binding.name.text;
      if (imported === 'Entity' || imported === 'ViewEntity') {
        decorators.add(binding.name.text);
      }
    }
  }
  const names = [];
  for (const statement of file.statements) {
    if (!ts.isClassDeclaration(statement)) continue;
    const entity = (ts.getDecorators(statement) ?? []).some((decorator) => {
      const expression = ts.isCallExpression(decorator.expression)
        ? decorator.expression.expression
        : decorator.expression;
      return ts.isIdentifier(expression) && decorators.has(expression.text);
    });
    if (!entity) continue;
    const exported = statement.modifiers?.some(
      (m) => m.kind === ts.SyntaxKind.ExportKeyword,
    );
    const defaultExport = statement.modifiers?.some(
      (m) => m.kind === ts.SyntaxKind.DefaultKeyword,
    );
    if (!statement.name || !exported || defaultExport) {
      throw new Error(
        `${filename}: une entité doit utiliser un export de classe nommé.`,
      );
    }
    names.push(statement.name.text);
  }
  return names;
}

export async function syncFeatureEntities({
  featuresRoot = resolve(backendRoot, 'src/features'),
  output = resolve(
    backendRoot,
    'src/persistence/feature-entities.generated.ts',
  ),
  check = false,
} = {}) {
  const imports = [];
  const registrations = [];
  let index = 0;
  for (const resource of resources) {
    const aliases = [];
    for (const file of await entityFiles(
      resolve(featuresRoot, resource, 'entities'),
    )) {
      for (const name of exportedEntities(await readFile(file, 'utf8'), file)) {
        const alias = `RegisteredEntity${index++}`;
        let path = relative(dirname(output), file)
          .replaceAll('\\', '/')
          .replace(/\.ts$/, '');
        if (!path.startsWith('.')) path = `./${path}`;
        imports.push(`import { ${name} as ${alias} } from '${path}';`);
        aliases.push(alias);
      }
    }
    registrations.push(`  ${resource}: [${aliases.join(', ')}],`);
  }
  const source = [
    '// Generated by npm run persistence:sync. Do not edit manually.',
    "import type { TypeOrmModule } from '@nestjs/typeorm';",
    ...imports,
    '',
    'type EntityRegistration = NonNullable<',
    '  Parameters<typeof TypeOrmModule.forFeature>[0]',
    '>;',
    `type FeatureName = ${resources.map((r) => `'${r}'`).join(' | ')};`,
    '',
    'export const featureEntities: Record<FeatureName, EntityRegistration> = {',
    ...registrations,
    '};',
    '',
  ].join('\n');
  const prettier = await import('prettier');
  const content = await prettier.format(source, {
    parser: 'typescript',
    singleQuote: true,
    trailingComma: 'all',
  });
  let current;
  try {
    current = await readFile(output, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (current !== content) {
    if (check)
      throw new Error('Registre périmé : lancer npm run persistence:sync.');
    await writeFile(output, content);
  }
  return { entities: index, changed: current !== content };
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const result = await syncFeatureEntities({
      check: process.argv.includes('--check'),
    });
    console.log(
      `Registre TypeORM : ${result.entities} entité(s), ${result.changed ? 'mis à jour' : 'à jour'}.`,
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
